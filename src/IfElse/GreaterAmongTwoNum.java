package IfElse;

public class GreaterAmongTwoNum {
    public static void main(String args[]){
        int num1 = 84;
        int num2 = 93;

        if(num2 > num1){
            System.out.println(num2 + "is greater");
        }else{
            System.out.println(num1 + "is lower");
        }
    }
}
